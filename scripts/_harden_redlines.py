SENTINEL = "（需结合"  # 残留软尾注特征，用于反向校验


def main():
    with open(SRC, "r", encoding="utf-8") as f:
        lines = f.readlines()
    changed = 0
    for old, new in HARDEN.items():
        hits = [i for i, ln in enumerate(lines) if old in ln]
        if not hits:
            # 已替换过（old 不在）→ 确认 new 已存在
            assert any(new in ln for ln in lines), f"既无旧串也无新串：{old[:20]}…"
            continue
        assert len(hits) == 1, f"旧串出现 {len(hits)} 次（应唯一）：{old[:20]}…"
        i = hits[0]
        assert new not in lines[i], f"新串已存在却仍匹配旧串：{old[:20]}…"
        lines[i] = lines[i].replace(old, new)
        changed += 1
    # 反向验证：不得再残留任何"需结合…综合研判"软尾注
    residual = [i + 1 for i, ln in enumerate(lines) if SENTINEL in ln and "综合研判" in ln]
    with open(SRC, "w", encoding="utf-8") as f:
        f.writelines(lines)
    print(f"OK: 硬化 {changed} 条软尾注；残留软尾注行数（应为0）: {len(residual)} -> {residual}")
    if residual:
        raise SystemExit("反向验证失败：仍存在未硬化的软尾注")


if __name__ == "__main__":
    main()
