def _blocks(src: str):
    """把源码切成 [(rule_id, start, end)]：以 `"id": "RL-…"` 为界。"""
    marks = [(m.group(1), m.start()) for m in
             re.finditer(r'"id":\s*"(RL-[A-Z]+-\d+)"', src)]
    out = []
    for i, (rid, pos) in enumerate(marks):
        end = marks[i + 1][1] if i + 1 < len(marks) else len(src)
        out.append((rid, pos, end))
    return out


def _check_verified() -> None:
    lib = json.loads((ROOT / "static" / "legal_library.json").read_text(encoding="utf-8"))
    have = {(x["law"], x["article"]) for x in lib}
    missing = [k for k in _VERIFIED if k not in have]
    if missing:
        print("✗ 下列条号在法规正文库中不存在，补丁中止：")
        for law, art in missing:
            print("   ", law, art)
        raise SystemExit(2)


def main(check_only: bool = False) -> int:
    _check_verified()
    src = io.open(TARGET, encoding="utf-8").read()
    orig = src
    changed_rules, errors = [], []

    # ── 步骤 0：条号漂移（2010/2019 版 → 2023 版《发票管理办法》）──
    #   虚开禁止在**第二十一条**；第二十二条是"税控装置"条款（原文已核）。
    #   10 条核心红线（有销无进/有进无销/品名背离/资金回流…）此前全部引到第二十二条。
    #   先处理复合引用（含"第二十三条"的那条），避免被通用规则截断。
    drift = [
        ("《发票管理办法》第二十二条、第二十三条", "《发票管理办法》第二十一条、第二十三条"),
        ("《中华人民共和国发票管理办法》第二十二条：任何单位和个人不得有下列虚开发票行为",
         "《中华人民共和国发票管理办法》第二十一条：任何单位和个人不得有下列虚开发票行为"),
        ("《发票管理办法》第二十二条", "《发票管理办法》第二十一条"),
    ]
    n_drift = 0
    for old, new in drift:
        n_drift += src.count(old)
        src = src.replace(old, new)
    if n_drift:
        print("修正条号漂移 %d 处（发票管理办法 第二十二条 → 第二十一条）" % n_drift)

    for rid, start, end in _blocks(src):
        if rid not in PATCH:
            continue
        block = src[start:end]
        newblock = block
        for old, new in PATCH[rid]:
            cnt = newblock.count(old)
            if cnt != 1:
                errors.append("%s: 期望 1 处 `%s`，实际 %d 处" % (rid, old[:60], cnt))
                continue
            newblock = newblock.replace(old, new, 1)
        if newblock != block:
            src = src[:start] + newblock + src[end:]
            changed_rules.append(rid)

    if errors:
        print("✗ 补丁遇到非唯一匹配，已中止（未写盘）：")
        for e in errors:
            print("   ", e)
        return 3

    print("将修改 %d 条规则：%s" % (len(changed_rules), ",".join(changed_rules)))

    # ── 后处理 1：把"单元素列表插入第二项"形成的嵌套 [[A, B]] 展平为 [A, B] ──
    #    （PATCH 里对单行 `["《X》"]` 的替换会产出嵌套；这是补丁自身的形式副作用，不是数据问题）
    flat_pat = re.compile(r'"legal_basis":\s*\[\s*\[([^\[\]]+?)\]\s*,?\s*\]', re.S)
    src, n_flat = flat_pat.subn(
        lambda m: '"legal_basis": [\n            %s\n        ]' % m.group(1).strip(), src)
    if n_flat:
        print("展平嵌套列表 %d 处" % n_flat)

    # ── 后处理 2：RL-SPT-020 的第二个规范性文件也补"无条文序号结构"声明 ──
    src = src.replace(
        "财政部关于民航发展基金等3项政府性基金有关政策的通知（财税〔2020〕72号：",
        "财政部关于民航发展基金等3项政府性基金有关政策的通知（财税〔2020〕72号，规范性文件，按全文适用：")

    if check_only:
        return 0 if src != orig else 1
    io.open(TARGET, "w", encoding="utf-8").write(src)
    print("已写入", TARGET)
    return 0


