def main() -> int:
    if not os.path.exists(PATH):
        print("缺少", PATH)
        return 1
    with open(PATH, encoding="utf-8") as f:
        data = json.load(f)

    bm = set((data.get("benchmarks") or {}).keys())
    unknown = [k for k in CORE_INPUTS if k not in bm]
    if unknown:
        print("[警告] core_inputs 含不在基准库的行业键（将被忽略）:", unknown)

    merged = dict(data.get("core_inputs") or {})
    merged.update({k: v for k, v in CORE_INPUTS.items() if k in bm})
    data["core_inputs"] = merged

    notes = data.get("_meta_rules") or {}
    if isinstance(notes, dict):
        notes["core_inputs"] = (
            "行业 → 主营业务成本对应的核心投入关键词。用于把进项发票区分为主营成本/期间费用。"
            "服务/流通类在此显式登记；制造/加工/贸易类由 product_chains(raw_materials+finished_goods) 运行时合并。"
        )
        data["_meta_rules"] = notes

    shutil.copyfile(PATH, PATH + ".bak-coreinputs")
    with open(PATH, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    # 复核
    with open(PATH, encoding="utf-8") as f:
        back = json.load(f)
    print("core_inputs 条目 =", len(back.get("core_inputs") or {}))
    print("product_chains 覆盖 =", len(back.get("product_chains") or {}))
    print("基准库行业数 =", len(back.get("benchmarks") or {}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
