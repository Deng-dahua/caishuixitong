# -*- coding: utf-8 -*-
"""疑点3 · D10 根因修复：把**材料名**从术语护栏的改写名单里移除。

根因（`engine/text_guardrails.py` 的 `_DIRECT_REPLACEMENTS`）
-----------------------------------------------------------
  ("全部银行账户流水", "与待证事实相关且依法获准核验的特定账户、期间和交易资料"),
  ("所有银行账户流水", "与待证事实相关且依法获准核验的特定账户、期间和交易资料"),
这两条本意是把**执法措施类**口语表述规范化，但它们的**匹配侧恰好就是资料名**
⇒ 护栏被应用到证据名/材料名上，把「全部银行账户流水（含已销户账户）」改写成
「与待证事实相关且依法获准核实的特定账户、期间和交易资料（含已销户账户）」
⇒ **材料名变成一份"不存在的东西"**，企业无法据此准备材料（疑点3 D10）。

为什么直接移除（而不是加豁免）
------------------------------
实测：这些规则改写出的执法表述在报告里出现 **0 次**
（"经权限、批准和必要性审查后"／"依法固定与待证事实相关"／"隔离询问"／"突击检查"… 全 0）
⇒ 它们**对报告零贡献**，唯一作用就是损坏材料名。
执法措施表述的规范化不属于本护栏的职责（那是别的功能），故此处**整条移除**，
并留注释说明，防止有人再加回来。

改动：仅删除 2 行 + 加注释，不动表结构、不动其他规则。
"""
import io
import os
import sys

ROOT = os.getcwd()
NL = chr(10)
CRLF = chr(13) + chr(10)
P = os.path.join(ROOT, "engine", "text_guardrails.py")

OLD = (
    '    ("全部银行账户流水", "与待证事实相关且依法获准核验的特定账户、期间和交易资料"),' + NL +
    '    ("所有银行账户流水", "与待证事实相关且依法获准核验的特定账户、期间和交易资料"),'
)
NEW = (
    '    # ★★ 2026-10-04（疑点3 D10 根因修复）：**这两条已移除**。' + NL +
    '    #   原规则：「全部银行账户流水」→「与待证事实相关且依法获准核验的特定账户、期间和交易资料」。' + NL +
    '    #   它本意是规范**执法措施类**口语表述，但**匹配侧恰好就是资料名** ⇒ 护栏被应用到' + NL +
    '    #   证据名/材料名上，把「全部银行账户流水（含已销户账户）」改写成一句法条措辞 ⇒' + NL +
    '    #   **材料名变成"企业无法准备的东西"**（读者根本不知道该交什么）。' + NL +
    '    #   实测：这些规则改写出的执法表述在报告里出现 **0 次** ⇒ 移除对报告零损失，' + NL +
    '    #   唯一作用就是损坏材料名。**不要加回来**；材料名一律逐字呈现，不做术语改写。'
)

raw = io.open(P, "r", encoding="utf-8", newline="").read()
crlf = CRLF in raw
t = raw.replace(CRLF, NL)
if t.count(OLD) != 1:
    print("!! 命中 %d 次" % t.count(OLD))
    sys.exit(2)
t = t.replace(OLD, NEW, 1)
io.open(P, "w", encoding="utf-8", newline="").write(t.replace(NL, CRLF) if crlf else t)
print("OK D10 根因已修（移除 2 条会损坏材料名的术语规则）")
