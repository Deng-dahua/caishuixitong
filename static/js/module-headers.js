/**
 * 注入标准化模块头部到子模块页面顶部
 * 防重复：同一页面ID在200ms内不重复注入
 */
var _lastInjectedPage = null;
var _lastInjectedTime = 0;
function injectModuleHeader(pageId) {
  var meta = MODULE_HEADERS[pageId];
  if (!meta) return;
  // 防重复
  if (pageId === _lastInjectedPage && Date.now() - _lastInjectedTime < 300) return;
  
  var container = document.getElementById('content-area');
  if (!container) return;
  
  // 找到当前页面容器（page-XX div 或第一个子元素）
  var pageDiv = container.querySelector('[id^="page-"]:not([style*="display: none"])');
  if (!pageDiv) pageDiv = container.firstElementChild;
  if (!pageDiv || pageDiv.classList.contains('mod-hdr')) return;
  
  // 避免重复注入
  if (pageDiv.querySelector('.mod-hdr')) return;
  
  var hdr = '<div class="mod-hdr" style="background:linear-gradient(135deg,#f8fafc 0%,#eff6ff 100%);border:1px solid #e2e8f0;border-radius:8px;padding:16px 20px;margin-bottom:20px;border-left:4px solid #2563eb">'
    + '<div style="font-size:18px;font-weight:800;color:#0f172a;margin-bottom:6px">' + meta.n + '</div>'
    + '<div style="font-size:13px;color:#475569;line-height:1.8;margin-bottom:10px">' + meta.d + '</div>'
    + '<div style="display:flex;gap:24px;font-size:11px;color:#94a3b8">'
    + '<span>所属：' + meta.g + '</span>'
    + '</div></div>';
  
  var tmp = document.createElement('div');
  tmp.innerHTML = hdr;
  var hdrEl = tmp.firstElementChild;
  pageDiv.insertBefore(hdrEl, pageDiv.firstChild);
  
  _lastInjectedPage = pageId;
  _lastInjectedTime = Date.now();
}
