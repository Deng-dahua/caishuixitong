def infer_province(text):
    """从任意文本（企业名称/流水摘要/地址）推断所属省级行政区。

    匹配顺序：城市名（更精确）→ 省名。都匹配不到返回空串。
    返回空串表示"无法推断"，调用方不得臆造。
    """
    s = str(text or "").strip()
    if not s:
        return ""
    # 1) 城市优先：先按较长城市名匹配，避免"西安"/"西宁"等歧义与短词误命中
    for city in sorted(_CITY_TO_PROVINCE.keys(), key=len, reverse=True):
        if city in s:
            return _CITY_TO_PROVINCE[city]
    # 2) 省名兜底
    for prov in _PROVINCE_NAMES:
        if prov in s:
            return prov
    return ""


def _party_name(value):
    """购销方字段可能是字符串，也可能是字典（含 name/company 等），统一取名称文本。"""
    if isinstance(value, dict):
        for key in ("name", "company", "party", "buyer_name", "seller_name", "customer", "supplier"):
            v = value.get(key)
            if v:
                return str(v)
        return ""
    return str(value or "")


def invoice_region(inv):
    """推断单张发票涉及的地区（省级）。

    优先使用显式地区字段（city/region/province/area）；
    这些字段当前解析链路并未写入，故实际主要走购销方名称推断。
    进项发票看销方（供应商所在地），销项发票看购方（客户所在地）；
    未知方向时两者都尝试。
    """
    if not isinstance(inv, dict):
        return ""
    # 1) 显式字段优先
    for key in ("city", "region", "province", "area", "buyer_city", "seller_city"):
        v = inv.get(key)
        if v:
            p = infer_province(v)
            if p:
                return p
            return str(v).strip()
    # 2) 按方向取对手方：进项→销方；销项→购方
    direction = str(inv.get("direction") or "").strip()
    if "进" in direction or "purchase" in str(inv.get("_file_type", "")).lower():
        order = ("seller", "buyer")
    elif "销" in direction or "sale" in str(inv.get("_file_type", "")).lower():
        order = ("buyer", "seller")
    else:
        order = ("seller", "buyer")
    for key in order:
        p = infer_province(_party_name(inv.get(key)))
        if p:
            return p
    return ""


def collect_regions(invs, self_names=()):
    """收集一批发票涉及的省级地区集合。

    self_names: 本企业名称（或其别名），用于排除本企业自身所在地，
                使"跨地区"只反映与外埠对手方的交易。留空则全部计入。
    """
    regions = set()
    self_regions = set()
    for n in (self_names or ()):
        p = infer_province(n)
        if p:
            self_regions.add(p)
    for inv in (invs or []):
        r = invoice_region(inv)
        if r:
            regions.add(r)
    if self_regions and len(regions) > len(self_regions):
        # 存在外埠对手方时，剔除本企业所在地，留下的即为外埠地区
        outside = regions - self_regions
        if outside:
            return outside
    return regions


def is_cross_region(invs, self_names=(), min_regions=2):
    """判断是否跨地区经营：涉及的外埠省份数 ≥ min_regions。"""
    return len(collect_regions(invs, self_names)) >= min_regions
