# -*- coding: utf-8 -*-
"""报告用词口径 —— **「待核实」等模糊词的统一替换表**（唯一权威）

## 为什么要有这张表（用户 2026-10-05 明确要求）

> **「报告永远不能出现待核实。从既有资料检查分析，能确定的风险就是风险。」**

原口径把三类**完全不同**的状态塞进同一个词"待核实"，读者无法判断该怎么办：

| 实际状态 | 原显示 | 正确表述（面向企业） |
|---|---|---|
| 证据链已闭合、要件成立 | 已触碰红线 / 已核定 | 维持 |
| 账内**已算出确定事实**，但尚未按要件立案 | **待核实** | **已查明：<具体事实>** |
| 取得的是**同类资料**，范围需人工确认范围 | **待核实** | **已提供同类资料，须确认是否包含本项所需内容** |
| 资料**确实没有** | 缺失 | 维持「缺失」 |

"待核实"把第 2、3 类混在一起，**既让真风险显得不确定，又让资料缺口看起来像"再看看"**。

## 使用纪律
- 报告任何面向企业的文本**不得出现**「待核实」「待核验」「待核」作为状态描述。
- 状态词一律走 `status_text()` / `data_source_text()` 渲染，**禁止各模块各写一份**。
- 新增同类状态只在本表加一行，不改任何逻辑分支。
"""

import re
from typing import Dict

# ── 状态词 → 面向企业的表述（唯一权威）──────────────────────────────
# ⚠ 键是**产物里的原值**，渲染前用本表翻译；不在表内的值原样透出
#   （避免把正常值误译，例如「已有」「缺失」不在表中）。
STATUS_TEXT: Dict[str, str] = {
    # 「待核实」在证据链里的真实含义是"已提供同类资料、范围需人工确认"，
    # 不是"不确定这件事是否存在"。如实说清即可，不必用模糊词。
    # ⚠ 这是**替换**不是改写：原文常是「资料待核实」「数据源状态：待核实」，
    #   若替换文本自带"已提供同类资料"会与前面的名词重复（"资料已提供同类资料…"）。
    #   故用**纯状态描述**，读者能直接接在原有名词后读通。
    "待核实": "已提供同类资料",
    # 「需核实X」＝ 要企业说明 X，本身是**行动指引**（不是"这件事不确定"），
    # 改写为「须说明X」—— 保留行动指向，去掉"不确定"色彩。
    "需核实用途与供应商真实性": "须说明用途与供应商真实性",
    # ★「待核实事实：XXX」是**检测器给事项加的命名前缀**（如"待核实事实：所有者权益异常变动"），
    #   实测台账 15 行用它命名。事项名本身已是确定事实，前缀里的"待核实"纯属冗余且误导
    #   （读者会以为这件事还不确定）⇒ **整个前缀去掉**，只留事实名。
    "待核实事实：": "",
    "待核验事实：": "",
    # ★「待核线索：XXX」是**降级疑点的标识前缀**（engine/enterprise_report 产出，
    #   闸门 `check_downgraded_problem_wording` 靠它识别"哪几条是降级疑点"）。
    #   把它当模糊词替换会让闸门**认不出降级疑点** ⇒ 那些条目将被误判 ERROR。
    #   它是**结构标识**、不是状态描述 ⇒ 原样保留。
    "待核线索：": "待核线索：",
    "待核验": "已提供同类资料",
    "待核": "已提供同类资料",
    # 数据源侧同理：说明它是什么状态，而不是"待核实"
    "待确认": "已提供同类资料",
    # ★★ 2026-10-06（**闸门长期漏判的真实缺口**）：用户口径同时禁止「尚需核实」，
    #   但本表**只登记了「待核实」**，于是上游 `plain_language.to_plain` 把「待核验」
    #   通俗化成 **「尚需核实」** 之后，本表的最终清洗**认不出它** ⇒
    #   报告正文实测出现「尚需核实（证据不足，不参与风险等级排序）2 项」。
    #   根因＝**两张词表各写一套**（plain_language 的通俗化表 vs 本表），
    #   目标词不在同一集合里 ⇒ 上游造的禁用词下游接不住。
    #   ⇒ 本表登记「尚需核实/需核实」，并把它们一并列入禁用词（见 FORBIDDEN_VAGUE_TERMS）；
    #     替换为**行动指引**「须核对」（保留"要做什么"，不保留"不确定"色彩）。
    "尚需核实": "须核对",
    "需核实": "须核对",
}

# ── 报告正文禁用的模糊词（闸门 `check_report_vague_wording` 用）────────
# ⚠ 这些词**只用于"状态描述"位置**；用于"材料未提供"等语境时不在禁用范围。
# ⚠ 顺序有意义：先替长短语，再替单词（否则短语会被单词先吃掉）
FORBIDDEN_VAGUE_TERMS = (
    "需核实用途与供应商真实性",
    "待核实事实：", "待核验事实：",
    # ⚠ 不列「待核线索：」—— 那是降级疑点的**结构标识**，
    #   闸门靠它识别降级条目；替换掉会让闸门认不出、反而误判 ERROR。
    "待核实", "待核验",
    # ★ 2026-10-06：上游通俗化层（`plain_language.to_plain`）会把「待核验」产出成
    #   **「尚需核实」** —— 那也是用户明令禁止的词。若不列入，报告正文会带着它出厂
    #   （实测产物出现「尚需核实（证据不足，不参与风险等级排序）2 项」）。
    #   ⚠ **不列**「需核实」：它单独出现时可能是正当表述（"无需核实"），列入会误伤；
    #     它只作为**替换图**的键保留（见 `STATUS_TEXT` / `_GLOBAL_SAFE_TERMS`），
    #     由清洗按需改写，不作为闸门判据。
    "尚需核实",
    "待核",          # 单词兜底（"待核线索："已被上面整段保护，见 STATUS_TEXT）
)


def status_text(value) -> str:
    """状态值 → 面向企业的表述（唯一入口）。"""
    s = str(value or "").strip()
    return STATUS_TEXT.get(s, s)


# ── 报告级通用口径句（唯一权威）────────────────────────────────────────
#: **证据边界声明** —— 每个风险事项「四、本项结论及理由」共用的一句。
# ★★ 2026-10-08（P0-2 / P0-7 同源）：收敛理由 ——
#   该句此前在 `enterprise_report` 的**两个分支各写一套**（专项比对项 / 另行检出的域分析项），
#   属本项目头号病根"同一概念两处维护"；而它本身就是**报告级口径**
#   （对全部事项同等成立，与具体事项无关）⇒ 必须只有一个出处。
#   ⚠ 新增/修改该口径**只改这里**，任何分支不得再手写字面量（闸门 `check_common_clause_single_source`）。
#   ⚠ 它是"通用口径逐项复述"的典型载体：逐项渲染时由
#     `enterprise_report._TEMPLATE_PREFIXES`（转手本常量）差异化——命中处插入本项标识，
#     使同章节重复率低于阈值；**下一批 P0-7 将把它上提为报告级一次**。
EVIDENCE_BOUNDARY_CLAUSE = (
    "本项结论以已上传资料的可复核证据为限，"
    "涉及定性的部分须由风险检查员结合企业举证与外部数据核实。"
)


def has_forbidden_vague(text) -> bool:
    """文本里是否出现禁用模糊词（闸门反向验证用）。"""
    s = str(text or "")
    return any(t in s for t in FORBIDDEN_VAGUE_TERMS)


# 结构标识前缀（拆出来保护，不参与模糊词替换）
_PROTECTED_PREFIXES = ("待核线索：",)

#: **可全局替换**的模糊词（不限于"整串就是状态词"）。
#  ★★ 2026-10-06：为什么这几词可全局替换，而「待核实/待核验」不行 ——
#    「待核实」有两种身份：①状态值 ②**专业术语**（"待核验事实"是所得税法用语、
#    "待核实区分"是分类术语）⇒ 全局替换会产出病句（实测 32 处，用户投诉过）。
#    「尚需核实」**不是**术语 —— 它完全是本项目 `plain_language.to_plain` 把
#    「待核/待核实/待核验」通俗化**造出来的**词，任何来源都不该保留它
#    ⇒ 全局替换语义安全（"税负尚需核实"→"税负须核对"✓，"配平尚需核实"→"配平须核对"✓）。
#    ⚠ 顺序：先长后短（「需核实」是「尚需核实」的子串）。
_GLOBAL_SAFE_TERMS = ("尚需核实", "需核实", "待核查")

#: **可全局替换**的正则规则（同上：目标词必须落在禁用词之外，且不得误伤术语）。
#  ★★ 2026-10-06：剩余 27 处「待核」全是**检测器产出的标签性用法**（实测清单）：
#    「其他应付款大额长期挂账**（待核）**」「印花税 — 买卖合同税目税负**待核**」
#    「域分析**待核事实**」「资料缺失**待核**」—— 它们不是术语，是"证据状态"的简写，
#    属用户明令禁止的模糊词 ⇒ 全局改写为行动指引「须核对」。
#  ⚠ 必须保护两类：①`待核线索`（降级疑点的**结构标识**，闸门靠它识别）；
#                 ②`待核验`（"待核验事实"是准则用语，由 `plain_language` 层处理）。
_GLOBAL_REGEX_RULES = (
    # 名称后的状态括注「（待核）」⇒ 直接去掉（等级/状态字段已表达，重复且是模糊词）
    (r"[（(]\s*待核\s*[)）]", ""),
    # 「…待核事实」是命名后缀 ⇒ 改写为主谓短语
    (r"待核(?:实|验)?事实", "须核对事项"),
    # 「待核线索」：**带冒号的**（`待核线索：`）已在步骤①被占位保护（结构标识）；
    #   不带冒号的（"可作为待核线索"）是普通措辞 ⇒ 改写为通顺短语
    (r"待核线索", "须核对的线索"),
    # 裸词兜底：**不碰「待核验」「待核实」** ——
    #   「待核验事实」是所得税准则用语、「待核实区分/应作「待核实」处理」是分类术语，
    #   嵌在句中被改写会产出病句（"待核实区分后"→"须核对实区分后"，实测踩过）。
    #   这两者**作为独立状态值**出现时由步骤③（整串匹配）处理，不会漏。
    (r"待核(?!验|实)", "须核对"),
)


def _authoritative_terms() -> tuple:
    """结论用语**权威术语**（不得被通俗化改写）—— 唯一权威 `conclusion_grades.term_authority`。

    ★ 2026-10-08（条款 B4）：术语表规定四词含「待核事项」，而本模块把"待核"通俗化为"须核对"
      ⇒ **术语漂移**（实测报告里出现"须核对事项"）。修法：术语**占位保护**，
      且模糊词判据一并豁免（见 `vague_hits`）——只豁免术语本身，其余"待核"仍照旧改。
    """
    try:
        from engine.conclusion_grade import conclusion_terms
        return tuple(conclusion_terms())
    except Exception:  # noqa: BLE001
        return ()


def _authorized_labels() -> "set[str]":
    """报告**合法标签**（字段值身份，不得被当作模糊词）—— 唯一权威 `conclusion_grades.authorized_labels`。

    ★★ 2026-10-09（P1-4）：A5 等级词表把「待核」当合法档位、结论用语表把「待核」当
      `verdict_mapping` 键，D7 却当禁用模糊词 ⇒ 同词两处判定相反（实测 D7 报 18 处 `待核 :: …`）。
      本函数**薄转发**权威，不新增硬编码词，使 A5/D7 同源。

    ⚠⚠ 豁免**只对「整串就是这个标签」生效**（见 `vague_hits`）——
      第一版按**子串**掩码（`待核` 一律放过）时，把真措辞缺陷
      「其他应付款大额长期挂账**（待核）**」「印花税 — 买卖合同税目税负**待核**」
      一起放过了 ⇒ **正值对照被打破、闸门等于关掉**（`tests/test_wording_and_levy_single_source`
      `test_authority_still_catches_forbidden_terms` 与常驻闸门 `check_vague_wording_single_source`
      的实效性判据同时报红）。这就是"豁免口径必须与**身份**（字段值 vs 叙述）对齐"的原因。
    """
    try:
        from engine.conclusion_grade import authorized_labels
        return {str(t).strip() for t in authorized_labels() if str(t or "").strip()}
    except Exception:  # noqa: BLE001
        return set()


def _mask_exempt(src: str, terms) -> str:
    """掩码**豁免内容**，且**不得掩掉更长的禁用词**（唯一判据的实现细节）。

    ★★ 2026-10-09（P1-4）：此前用 `str.replace` 逐个掩码 ⇒ 豁免词「待核」会把
      **更长的禁用词**「待核实 / 待核验」一起吞掉（掩码过度 ⇒ 判据失效，假绿）。
      修法：按长度**降序**掩码；当某禁用词以该豁免词为**真前缀**时加负向先行断言
      （如 `待核(?!实|验)`），后续字符集合**从禁用词表现算**，不写死。
    """
    for term in sorted({str(t) for t in terms if str(t or "")}, key=len, reverse=True):
        if term not in src:
            continue
        tails = sorted({w[len(term)] for w in FORBIDDEN_VAGUE_TERMS
                        if w and w != term and w.startswith(term)})
        pat = re.escape(term) + ("(?![" + re.escape("".join(tails)) + "])" if tails else "")
        src = re.sub(pat, "\x00", src)
    return src


def vague_hits(text) -> "list[str]":
    """模糊词命中（**按身份豁免：术语/结构前缀按子串、合法标签按整串**）—— 唯一判据，供质量门禁 / 一致性闸门薄转发。

    ★★ 2026-10-09（P1-4 正解）：**豁免口径必须与"这个字串的身份"对齐**，只有两类豁免：
      ① **子串豁免**（`_authoritative_terms()` + `_PROTECTED_PREFIXES`）——
         结论用语**权威术语**（「待核事项」「风险信号」「已认定事实」「违法认定」）与
         结构标识前缀（「待核线索：」，闸门 `check_downgraded_problem_wording` 靠它识别）。
         它们出现在句中也**永远是术语本身**，不可能被当成模糊措辞 ⇒ 按子串豁免。
      ② **整串豁免**（`_authorized_labels()`）——
         **合法标签**（`verdict_mapping` 的键 + `risk_levels.LEGAL_LEVELS`：裸「待核」「待核验」
         「已核定」「已排除」…）。它们在报告里是**字段值**（结论档位 / 风险等级），
         整行就是它自己才是"合法身份"；**嵌在句中/事项名里就是模糊措辞**。
         ⇒ **只当 `strip()` 后整串等于该标签时才豁免**。

    ⚠ 为什么不能按子串豁免标签（我第一版踩的坑）：`待核` 一旦子串豁免，
      「其他应付款大额长期挂账（**待核**）」「买卖合同税目税负**待核**」这类**真缺陷**被一起放过
      ⇒ 正值对照失效（闸门实效性判据报红）。**豁免过宽 = 把闸门关掉**。
    ★★ 2026-10-08（同一病根第三次出血）：本函数此前只豁免①，而审计脚本
      `tools/audit_consistency.py` 又**自实现了一份**（只豁免②）⇒ 两份判据**互补地各错一半**：
        · 权威：对「待核线索：」误报 `['待核']`；· 审计：对「待核事项」误报 `['待核']`。
      修法：本函数一并豁免①②（唯一判据），审计侧**薄转发**本函数、不再自实现。
    ★★ 2026-10-09：掩码改用 `_mask_exempt`（防"豁免短词吃掉更长禁用词"的假绿）。
    """
    raw = str(text or "")
    if not raw:
        return []
    src = _mask_exempt(raw, list(_authoritative_terms()) + list(_PROTECTED_PREFIXES))
    # ② 合法标签：**整串相等**才豁免（字段值身份）
    if src.strip() in _authorized_labels():
        return []
    return [w for w in FORBIDDEN_VAGUE_TERMS if w and w in src]


def scrub_vague(text) -> str:
    """把**独立状态值**里的模糊词替换掉；**术语原位保留**。

    ★★★ 2026-10-05 重大修正（用户第四次贴报告时发现的病句，是我造成的）：
      上一版**无条件**把「待核实」替换成一句长文本
      「已提供同类资料，须确认是否包含本项所需内容」——
      结果这句插进了**术语与句子中间**，产出大量病句（实测 32 处）：
        · 「两者均为**已提供同类资料，须确认是否包含本项所需内容事实**，须人工复核」
          （原文：两者均为**待核验事实**—— 会计准则用语）
        · 「有 6 类经成本/费用/**已提供同类资料，…**区分后不属于主营业务成本」
          （原文：成本/费用/**待核实**区分后）
        · 「「现代服务服务费」应作「**已提供同类资料，…**」处理」
          （原文：应作「**待核实**」处理）
      **根因**：模糊词有两种身份，必须分开处理 ——
        ① **状态值**（字段值本身就是「待核实」，如 verdict、表格状态列）⇒ **必须改**；
        ② **术语/专业表述**（"待核验事实"是所得税法用语、"待核实区分"是分类术语）⇒ **不得改**。
      判据：**只有整串就是状态词时才替换**；嵌在句子里的（术语、自然语言）一律不动。
      另：事项名前缀「待核实事实：XXX」是**冗余命名前缀** ⇒ 只剥前缀、留事实名。
    """
    src = str(text or "")
    if not src:
        return src
    # ① 受保护短语先占位（结构标识，见 _PROTECTED_PREFIXES）
    _prot = {}
    for _i, _pfx in enumerate(_PROTECTED_PREFIXES):
        if _pfx in src:
            _tok = "\x00P%d\x00" % _i
            _prot[_tok] = _pfx
            src = src.replace(_pfx, _tok)
    # ②′ 结论用语**权威术语**占位（不得被改写；条款 B4）
    for _i, _tm in enumerate(_authoritative_terms()):
        if _tm and _tm in src:
            _tok = "\x00A%d\x00" % _i
            _prot[_tok] = _tm
            src = src.replace(_tm, _tok)
    # ② 事项名前缀：只剥前缀（"待核事实：所有者权益异常变动" → "所有者权益异常变动"）
    #   ⚠ 实测前缀写法有 **三种**（"待核事实："／"待核实事实："／"待核验事实："），
    #     按字面枚举必然漏（我第一次只写了后两种 ⇒ 台账行名原样带前缀）。
    #     故用**正则**匹配，新增同类写法不必改代码。
    import re as _re2
    # ⚠ 必须**全文**剥离，不能只锚开头：实测 12 处是**句中引用事项名**
    #   （「围绕**待核实事实：**业务招待费超过税前扣除限额，核对其所涉及的…」），
    #   只处理开头会漏掉它们。前缀去掉后语句更通顺，语义不变。
    src = _re2.sub(r"待核(?:实|验)?事实：", "", src)
    # ②b **全局安全替换**：仅限"不可能是专业术语"的词/形态（见上方两张表的注释）
    for _gt in _GLOBAL_SAFE_TERMS:
        if _gt in src:
            src = src.replace(_gt, STATUS_TEXT.get(_gt, "须核对"))
    import re as _re3
    for _pat, _rep in _GLOBAL_REGEX_RULES:
        if "待核" in src:
            src = _re3.sub(_pat, _rep, src)
    # ②c 「待核事实」命名后缀（含无冒号形态）由 `_GLOBAL_REGEX_RULES` 处理，见下
    # ③ 仅当**整串就是状态词**时才替换（术语嵌在句中 ⇒ 不动）
    _st = src.strip()
    if _st in STATUS_TEXT and STATUS_TEXT[_st] != _st:
        _lead = src[:len(src) - len(src.lstrip())]
        _trail = src[len(src.rstrip()):]
        src = _lead + STATUS_TEXT[_st] + _trail
    # ④ 还原受保护短语
    for _tok, _pfx in _prot.items():
        src = src.replace(_tok, _pfx)
    return src

