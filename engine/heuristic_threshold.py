# -*- coding: utf-8 -*-
"""内部参照线（heuristic threshold）—— **全系统唯一权威**（2026-10-05 新增）

## 为什么要有这张表（疑点7 D5 的根因）
检测器判定"异常"时需要一把尺子，但这把尺子**不是法定标准、也不是行业基准**，
而是开发者据经验取的数。问题不在于"取了经验值"（取阈值本身是必要的，
没有阈值就无法从连续量里判断异常），而在于：

1. **阈值不出现在任何一份要件清单里** —— 读者在报告里找不到它的出处；
2. **阈值没有免责声明** —— 读者会以为"低于 1% 即构成违法"，
   而它其实只是"值得去看这一项"的线索；
3. **同一个量在不同模块各写一份字面量** —— 改一处、漏三处，闸门也拦不住。

事故（真实产物，疑点7）：报告写「结果 0.01%，**低于 1% 参照线**」，
而该红线的 5 条构成要件里**没有任何一条涉及贡献率** ⇒ 这个 1% 成了
**唯一的触发依据**，却既无出处、也不构成判定依据。同一缺陷在
`financial_analyzer` 里还有 3 处（申报/销项 90%、未开票 30%、应收转次 20 次），
`structure_mismatch_detector` 里还有 3 处（费用/成本 高 80%、低 2%）。

## 唯一权威与纪律
- 本表是**内部参照线的唯一出处**。新增同类判据只在此加一行，**不改任何逻辑分支**。
- 每行必须写清：`basis`（出处说明/为何取这个数）与 `caution`（免责措辞）。
- 报告层渲染统一走 `format_heuristic()`，**不得**再手写"（低于 X 参照线）"字样。
- `legal=True` 的行是**法定标准**（如业务招待费 5‰），不是内部经验值，
  不适用免责措辞，渲染时不加"参照线"三字。
"""

from typing import Any, Dict, Tuple

# ══════════════════════════════════════════════════════════════════
# 内部参照线表：键 = 语义标识，值 = (阈值, 比较方向, 出处说明, 免责措辞)
#   比较方向："lt" 表示低于阈值即异常；"gt" 表示高于阈值即异常
# ══════════════════════════════════════════════════════════════════
HEURISTIC_THRESHOLDS: Dict[str, Tuple[float, str, str, str]] = {
    # ── 企业所得税贡献率（账面所得税费用 / 主营业务收入）低于 1% ──
    #   出处：行业经验值。微利/亏损企业、所得税优惠（高新15%、小微5%等）、
    #   前期亏损弥补、研发加计扣除都会把贡献率压到极低；
    #   1% 是"明显偏低、值得核查"的筛选线，**不是**违法认定标准。
    "cit_contribution_ratio": (
        0.01, "lt",
        "行业经验筛选值。低于该值时贡献率明显偏低，值得进一步核查",
        "内部经验筛选值，非法定标准，仅提示关注、不构成判定依据",
    ),
    # ── 增值税申报销售额 / 销项发票不含税金额 低于 90% ──
    #   出处：行业经验值。差额部分可能已开票未申报；取值留出正常的时间性差异。
    "decl_vs_invoice_ratio": (
        0.90, "lt",
        "行业经验筛选值。用于提示已开票未申报的可能性",
        "内部经验筛选值，非法定标准，仅提示关注、不构成判定依据",
    ),
    # ── 未开票收入占申报销售额 比例 高于 30% ──
    "unbilled_ratio": (
        0.30, "gt",
        "行业经验筛选值。用于提示未开票收入占比偏高",
        "内部经验筛选值，非法定标准，仅提示关注、不构成判定依据",
    ),
    # ── 主营业务收入 / 应收账款 高于 20 次（近似年转次数）──
    "receivable_turns": (
        20.0, "gt",
        "行业经验筛选值。以期末应收账款近似平均余额，口径为估算",
        "内部经验筛选值，口径为估算，仅提示关注、不构成判定依据",
    ),
    # ── 期间费用 / 销售成本 接近或超过成本（≥80%）──
    "expense_cost_ratio_high": (
        0.80, "gt",
        "行业经验筛选值。费用接近或超过成本，多数行业不合理",
        "内部经验筛选值，非法定标准，仅提示关注、不构成判定依据",
    ),
    # ── 期间费用 / 销售成本 极低（<2%）──
    #   出处：行业经验值。费用极低可能存在费用未如实归集。
    "expense_cost_ratio_low": (
        0.02, "lt",
        "行业经验筛选值。费用极低可能存在费用未如实归集",
        "内部经验筛选值，非法定标准，仅提示关注、不构成判定依据",
    ),
}

# 法定标准（非内部经验值）：业务招待费按发生额 5‰ 扣除，**有法律出处**，
#   因此不使用"参照线"措辞、不加免责声明。
LEGAL_THRESHOLDS: Dict[str, Dict[str, Any]] = {
    "entertainment_5permille": {
        "ratio": 0.005,
        "basis": "《企业所得税法实施条例》第四十三条：业务招待费支出按发生额的 5‰ 在税前扣除",
    },
}


def get_threshold(key: str):
    """取内部参照线定义；未登记返回 None（调用方须显式处理，不得静默套用别的键）。"""
    return HEURISTIC_THRESHOLDS.get(str(key or "").strip())


def format_heuristic(key: str, value: Any, *, fmt: str = "pct", raw_value: str = "") -> str:
    """渲染"结果 + 参照线 + 出处 + 免责"整句，**报告层唯一入口**。

    `raw_value` 用于"以期末应收近似平均余额"这类**口径估算**的补充说明。
    返回整句，直接进 `how_found`，避免各检测器各写一份字面量。
    """
    d = get_threshold(key)
    if not d:
        # 未登记 ⇒ 不静默编一句免责，返回原值由调用方自行处理
        return str(value)
    thr, direction, basis, caution = d
    num = ("%.2f%%" % (float(value) * 100)) if fmt == "pct" else (
        ("%.1f" % float(value)) if fmt == "num" else str(value))
    thr_txt = ("%.2f%%" % (thr * 100)) if fmt == "pct" else ("%.1f" % thr)
    # `raw_value` 只在调用方需要**补口径**（如"以期末应收近似平均余额"）时传；
    #   若与 `basis` 里的口径说明重复，调用方不传即可，此处做一次去重兜底。
    extra = ""
    if raw_value and raw_value not in basis and raw_value not in caution:
        extra = "；口径：%s" % raw_value
    return "%s %s %s 参照线（%s；%s%s）" % (
        num, "低于" if direction == "lt" else "高于", thr_txt, basis, caution, extra)
