REDLINES: List[Dict] = (
    _VAT_REDLINES + _INCOME_REDLINES + _COST_REDLINES + _FUND_REDLINES
    + _INVENTORY_REDLINES + _PAYROLL_REDLINES + _CIT_REDLINES
    + _COUNTERPARTY_REDLINES + _ASSET_REDLINES + _OTHER_REDLINES
)

_BY_ID: Dict[str, Dict] = {r["id"]: r for r in REDLINES}

DOMAIN_ORDER = [
    "发票", "收入", "成本", "资金", "存货", "工资社保",
    "关联交易", "所得税", "其他税费",
]


def all_redlines() -> List[Dict]:
    """返回全部红线（只读副本）"""
    return [dict(r) for r in REDLINES]


def get_redline(redline_id: str) -> Optional[Dict]:
    """按编号取红线"""
    r = _BY_ID.get(str(redline_id or "").strip())
    return dict(r) if r else None


def by_domain(domain: str) -> List[Dict]:
    """按风险域取红线"""
    return [dict(r) for r in REDLINES if r.get("domain") == domain]


def domains() -> List[str]:
    """已定义的风险域"""
    seen, out = set(), []
    for d in DOMAIN_ORDER:
        if any(r.get("domain") == d for r in REDLINES):
            seen.add(d)
            out.append(d)
    for r in REDLINES:
        d = r.get("domain")
        if d and d not in seen:
            seen.add(d)
            out.append(d)
    return out


def match_redlines(text: str, domain: Optional[str] = None, limit: int = 3) -> List[Dict]:
    """
    依据发现文本匹配红线。

    匹配优先级：
      1) 命中红线的 match_hints 关键词；
      2) 命中红线名称中的核心词；
      3) 命中涉嫌描述（suspect）中的核心词。
    同域优先。
    """
    t = str(text or "")
    if not t:
        return []
    scored = []
    for r in REDLINES:
        score = 0
        for hint in (r.get("match_hints") or []):
            if hint and hint in t:
                score += 10
        name = r.get("name", "")
        # 名称中的「：」前主词
        main_word = name.split("：")[0]
        if main_word and len(main_word) >= 3 and main_word in t:
            score += 8
        for kw in (r.get("taxes") or []):
            if kw and kw in t:
                score += 1
        if domain and r.get("domain") == domain:
            score += 3
        if score > 0:
            scored.append((score, r))
    scored.sort(key=lambda x: (-x[0], x[1]["id"]))
    return [dict(r) for _, r in scored[:limit]]


def stats() -> Dict:
    """红线库统计"""
    return {
        "version": KNOWLEDGE_VERSION,
        "total": len(REDLINES),
        "by_domain": {d: len(by_domain(d)) for d in domains()},
    }
