"""
税务红线知识库（行业无关）—— 风险检查方法论的地基
==================================================

方法论立场（2026-09-06 确立）
--------------------------------------------------
1. 税务红线不因行业而变。制造业、餐饮业、建筑业的规避手法不同，但
   「触碰的红线」是同一套：隐匿收入、虚列成本、虚开发票、资金回流、
   账外循环、工资社保不实。行业只影响「线索长什么样」，不影响
   「红线是什么」。因此本库按「红线」组织，不按行业组织。
2. 红线 = 客观构成要件 + 法定依据。符合构成要件即构成「税务疑点」，
   不再输出「待核事实：XXX核验」这类没有红线的空壳。
3. 疑点 ≠ 定性。触红只表示「有法定情形需要核实」，是否构成违法由
   证据链闭合 + 论证裁决决定（见 argumentation.py）。

每条红线的六要素
--------------------------------------------------
  id           红线编号（域-序号）
  name         红线名称（报告标题用，禁止用「XXX核验」代替）
  domain       风险域
  taxes        涉及税种
  suspect      触红涉嫌的税务问题（用「涉嫌」，不预断定罪）
  legal_basis  法定依据
  constituents 客观构成要件（机器可判定的事实条件，全部满足才触红）
  clue_chain   线索链模板：这个疑点是怎么从资料里浮现出来的（逐级可回溯）
  evidence_chain 证据链模板：要坐实/排除这条红线，需要组织哪些证据
  justifications 正当理由（反证）：存在即可能不触红，必须同标准核对
  required_materials 核查本条红线必须的资料（缺失即产生风险盲区）
  remedy       补证要求
"""

