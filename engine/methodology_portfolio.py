def resolve_industry_code(industry: str) -> str:
    text = str(industry or "").strip().lower()
    if not text:
        return ""
    for code in OVERLAY_CODES + INDUSTRY_CODES:
        if text == code.lower() or text.startswith(f"{code.lower()} "):
            return code
        if any(alias.lower() in text for alias in INDUSTRY_ALIASES.get(code, ())):
            return code
    return ""


