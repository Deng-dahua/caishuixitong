def _read(filename: str) -> Any:
    return json.loads((STATIC / filename).read_text(encoding="utf-8-sig"))


def _unique(values) -> list:
    output = []
    for value in values or []:
        value = str(value or "").strip()
        if value and value not in output:
            output.append(value)
    return output


def _split_path(value: str) -> list[str]:
    return [part.strip() for part in str(value or "").split("→") if part.strip()]


def _stage_action(part: str) -> str:
    verbs = ("按", "把", "从", "确认", "识别", "核验", "检查", "复核", "重建", "追踪", "判断", "分析", "复算", "区分", "建立", "连接", "处理", "穿透", "盘点", "列明", "拆分", "定位", "汇总", "验证", "测试", "下载", "适用")
    action = str(part or "").strip()
    if action.startswith(verbs):
        return f"{action}，并记录与前后环节的数量、金额、期间或权利义务连接"
    return f"核验{action}，并记录与前后环节的数量、金额、期间或权利义务连接"


