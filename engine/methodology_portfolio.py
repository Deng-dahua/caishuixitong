def _source_gates(sources: list[str]) -> list[dict]:
    candidates = _unique(sources)
    if not candidates:
        return []
    groups = []
    for index, source in enumerate(candidates[:4], 1):
        accepted = [source]
        if index == 1:
            accepted.extend(["合同权利义务", "会计核算"])
        elif index == 2:
            accepted.extend(["发票申报", "税费申报"])
        elif index == 3:
            accepted.extend(["资金结算", "支付结算"])
        groups.append({"name": source, "any": _unique(accepted)})
    return groups


