# 红线需求名 → 识别信息（单一权威）
_SUPPLEMENTARY_RECOGNITION = {
    name: {"doc_type": dt, "filename_kws": kws, "extra_cats": extra}
    for name, dt, kws, extra in _SUPP_ENTRIES
}

# 全部补充类别名（含"发票"——它由发票类 doc_type 双映射提供，不进识别表避免误吞正常发票）
_SUPPLEMENTARY_CATEGORIES = [name for name, _, _, _ in _SUPP_ENTRIES] + ["发票"]


def _recognize_supplementary(filename, text=None):
    """文件名（优先）或文本命中补充资料关键词 → 返回 doc_type，否则 None。

    取**最长命中关键词**的条目，避免短词误路由（如"合同"误吞"代理协议"）。
    仅在明确命中补充资料关键词时返回，普通资料（银行流水/发票/合同…）返回 None，
    交还内容指纹链路正常识别。
    """
    fn = (filename or "").lower()
    best = None
    best_len = 0
    for _name, _info in _SUPPLEMENTARY_RECOGNITION.items():
        for _kw in _info["filename_kws"]:
            if _kw.lower() in fn and len(_kw) > best_len:
                best = _info["doc_type"]
                best_len = len(_kw)
                break
    if best is None and text:
        _t = (text or "")[:2000].lower()
        for _name, _info in _SUPPLEMENTARY_RECOGNITION.items():
            for _kw in _info["filename_kws"]:
                if _kw.lower() in _t and len(_kw) > best_len:
                    best = _info["doc_type"]
                    best_len = len(_kw)
                    break
    return best


def supplementary_doc_type_to_category(doc_type):
    """给定补充 doc_type → (类别名, 额外并回的 15 类类别)。供 _DOC_TYPE_TO_CATEGORY 复用。"""
    for _name, _dt, _kws, _extra in _SUPP_ENTRIES:
        if _dt == doc_type:
            return (_name,) + tuple(_extra)
    return ()
