"""补充自证资料识别（P3.5，2026-09-27）。

背景
────
红线库 ``required_materials`` 中，有一部分资料名既不是系统 15 类必查资料、
也不在 ``analysis_coverage._MATERIAL_SUPERCLASS`` 超类表（审计 WARN 的"漂移名"，
共 73 个）。它们是企业**真实拿得到、也该上传**的凭证/台账/文书（完税凭证、出口报关单、
盘点表、不动产权证……）。此前这些资料即使上传，也因不匹配任何内容指纹被归入
``generic_data``，**不计入"已提供"→ 红线的"需补充提供"永远变不成"已提供"**（传了也白传）。

设计原则（贴合审计教义，不冒充）
─────────────────────────────
证据链 ``build_evidence_chain`` 的"已有/待核/缺失"三态要求：**只有资料名逐字命中**
才算"已有"，类别相关只能算"待核"。因此本模块**不为这些资料编造映射去冒充某个 15 类**，
而是把每一种漂移名登记为它**自己的补充类别**（类别名与红线需求名完全一致）：

- 企业上传后，由文件名识别为对应 ``doc_type``；
- ``doc_type`` 经 ``enterprise_report._DOC_TYPE_TO_CATEGORY`` 映射到**与红线需求名
  完全一致的类别名**（少数确属某 15 类子类的，额外并回该 15 类，如 BOM→进销存台账）；
- 红线证据链对资料名逐字匹配 → 上传即判定"已有"，把"需补充提供 X"翻转成"已提供 X"。

数据表式：新增一种补充资料只需在 ``_SUPP_ENTRIES`` 加一行
``(类别名/资料名, doc_type, [文件名关键词], [额外并回的类别])``，
并在 ``enterprise_report._DOC_TYPE_TO_CATEGORY`` 加一行映射（见本模块底部常量）。
绝不硬分类冒充已提供。
"""
